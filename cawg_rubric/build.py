"""Assemble composable statement files into built CAWG rubrics.

Adapted from the C2PA Conformance Task Force rubric builder
(https://github.com/c2pa-org/conformance-public,
asset-rubrics/build_conformance_rubrics.py at commit f22ce0a), used under
CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Spec-version variable
injection was removed; globals loading, used-globals filtering and ID-based
deduplication are unchanged; recipes now come from cawg_rubric/suite.yml and
plugin manifests (see manifest.py). See NOTICE.

Usage:
    python -m cawg_rubric.build                     # the core rubrics
    python -m cawg_rubric.build --plugin PATH       # a plugin's rubrics, into its build_dir
"""

import copy
import os
import re
import sys

import yaml

from . import __version__
from .manifest import ManifestError, load_project, load_suite

# Fixed so that builds are reproducible.
CORE_DATE = "2026-10-10T00:00:00Z"
CORE_HEADER = "# GENERATED by `python -m cawg_rubric.build` - edit cawg_rubric/rubrics/composables/ instead.\n"


# Custom representer to preserve literal block style for long or multiline strings (expressions)
def str_presenter(dumper, data):
    if len(data.splitlines()) > 1 or len(data) > 80:
        return dumper.represent_scalar('tag:yaml.org,2002:str', data, style='|')
    return dumper.represent_scalar('tag:yaml.org,2002:str', data)


yaml.add_representer(str, str_presenter)


def load_globals(filepath, _visited=None):
    """Load variables and expressions from a globals file, recursively following include: lists."""
    if _visited is None:
        _visited = set()
    filepath = os.path.abspath(filepath)
    if filepath in _visited:
        return {'variables': {}, 'expressions': {}}
    _visited.add(filepath)

    with open(filepath, 'r') as f:
        doc = yaml.safe_load(f)

    result = {
        'variables':   dict(doc.get('variables',   {}) or {}),
        'expressions': dict(doc.get('expressions', {}) or {}),
    }

    base_dir = os.path.dirname(filepath)
    for name in (doc.get('include') or []):
        included = load_globals(os.path.join(base_dir, name), _visited)
        # Included file provides the base; current file's keys win on conflict.
        result['variables']   = {**included['variables'],   **result['variables']}
        result['expressions'] = {**included['expressions'], **result['expressions']}

    return result


def filter_used_globals(statements, all_globals):
    """
    Scan statement expressions and return only the variables/expressions
    that are actually referenced, following transitive expression dependencies.
    """
    used_vars = set()
    used_exprs = set()
    for stmt in statements:
        if not isinstance(stmt, dict):
            continue
        expr = stmt.get('expression', '')
        if not isinstance(expr, str):
            continue
        used_vars.update(re.findall(r'\$[A-Za-z_]\w*', expr))
        used_exprs.update(re.findall(r'_[A-Za-z_]\w*(?=\()', expr))

    # Transitively include expressions called by already-included expressions.
    frontier = set(used_exprs)
    while frontier:
        next_frontier = set()
        for name in frontier:
            body = all_globals['expressions'].get(name, '')
            if not isinstance(body, str):
                continue
            used_vars.update(re.findall(r'\$[A-Za-z_]\w*', body))
            for dep in re.findall(r'_[A-Za-z_]\w*(?=\()', body):
                if dep not in used_exprs:
                    next_frontier.add(dep)
            used_exprs.update(re.findall(r'_[A-Za-z_]\w*(?=\()', body))
        frontier = next_frontier

    variables   = {k: v for k, v in all_globals['variables'].items()   if k in used_vars}
    expressions = {k: v for k, v in all_globals['expressions'].items() if k in used_exprs}
    return variables, expressions


def load_component_file(path):
    """Return the statements in a composable file (an absolute path)."""
    with open(path, 'r') as f:
        statements = []
        for d in yaml.safe_load_all(f):
            if isinstance(d, list):
                statements.extend(d)
            elif isinstance(d, dict) and "id" in d:
                statements.append(d)
        return statements


def _statements_of(paths):
    statements_map = {}
    for path in paths:
        for s in load_component_file(path):
            if isinstance(s, dict) and "id" in s:
                # Later files override earlier files (deduplication by ID).
                statements_map[s["id"]] = s
    return list(statements_map.values())


def _severity(stmt):
    if stmt.get("failIfMatched"):
        return "fail"
    if stmt.get("warnIfMatched"):
        return "warn"
    return "boolean"


def tighten(stmt, plugin):
    """Return a copy of a warnIfMatched statement that fails instead."""
    stmt = copy.deepcopy(stmt)
    stmt.pop("warnIfMatched", None)
    stmt["failIfMatched"] = True
    note = f"[Tightened from a warning to a failure by {plugin}.]"
    stmt["description"] = f"{stmt['description']} {note}" if stmt.get("description") else note
    # Keep the key order of hand-written statements: id, description, specSection, failIfMatched, ...
    order = ["id", "description", "specSection", "failIfMatched", "expression", "reportText"]
    return {k: stmt[k] for k in order if k in stmt} | {k: v for k, v in stmt.items() if k not in order}


def profile_problems(project, profile):
    """Guardrail violations in one plugin profile: statement IDs and overrides."""
    problems = []
    where = f"profile {profile.id}"
    base = {s["id"]: s for p in profile.extends for s in _statements_of(p.composables)}
    try:
        own = _statements_of(profile.composables)
    except (OSError, yaml.YAMLError) as e:
        return [f"{where}: {e}"]
    for s in own:
        category = s["id"].split(":", 1)[0] if ":" in s["id"] else None
        if category != project.statement_prefix:
            problems.append(f"{where}: statement {s['id']!r} must be named "
                            f"{project.statement_prefix}:<name>")
    for sid, value in profile.overrides.items():
        if sid not in base:
            problems.append(f"{where}: override {sid!r} is not a statement of "
                            f"{', '.join(p.qualified_id for p in profile.extends) or 'any extended profile'}")
        elif value != "fail":
            problems.append(f"{where}: override {sid!r}: {value!r} is not allowed; plugins can only "
                            "tighten a warning to 'fail', never weaken or disable a statement")
        elif _severity(base[sid]) == "fail":
            problems.append(f"{where}: override {sid!r} is already a failure")
        elif _severity(base[sid]) == "boolean":
            problems.append(f"{where}: override {sid!r} is a true/false statement with no warning to tighten")
    return problems


def assemble(profile, project=None):
    """Return (metadata, statements) for a profile, in memory.

    A core profile is its composables. A plugin profile is the statements of the
    core profiles it extends, with overrides applied, followed by the plugin's own
    statements. Globals are the core globals plus the plugin's.
    """
    suite = load_suite()
    all_globals = load_globals(suite.globals_path)
    if project is None or project.kind == "core":
        statements = _statements_of(profile.composables)
        issuer, version, date = "CAWG Test Suite", __version__, CORE_DATE
    else:
        if project.globals_path:
            mine = load_globals(project.globals_path)
            all_globals = {k: {**all_globals[k], **mine[k]} for k in all_globals}
        statements = []
        for base in profile.extends:
            for s in _statements_of(base.composables):
                if profile.overrides.get(s["id"]) == "fail" and _severity(s) == "warn":
                    s = tighten(s, project.name)
                statements.append(s)
        seen = {s["id"] for s in statements}
        statements += [s for s in _statements_of(profile.composables) if s["id"] not in seen]
        issuer, version, date = project.issuer, project.version, project.date or CORE_DATE

    variables, expressions = filter_used_globals(statements, copy.deepcopy(all_globals))
    metadata = {
        "rubric_metadata": {
            "name": profile.name,
            "issuer": issuer,
            "date": date,
            "version": version,
            "language": "en",
        }
    }
    if variables:
        metadata["variables"] = variables
    if expressions:
        metadata["expressions"] = expressions
    return metadata, statements


def render_rubric(metadata, statements, header):
    return (header
            + yaml.dump(metadata, sort_keys=False, width=1000, allow_unicode=True)
            + "\n---\n\n"
            + yaml.dump(statements, sort_keys=False, width=1000, allow_unicode=True))


def plugin_header(project, profile):
    extends = ", ".join(f"{p.qualified_id}" for p in profile.extends) or "nothing"
    lines = [
        f"# GENERATED by `cawg-suite build --plugin` from {project.name} {project.version}",
        f"# profile {profile.id}, extending {extends} (cawg-test-suite {__version__}).",
        "# Edit the plugin's composables instead.",
    ]
    if profile.overrides:
        lines.append("# Tightened to failures: " + ", ".join(sorted(profile.overrides)))
    return "\n".join(lines) + "\n"


def rendered(project, profile):
    """The text of a profile's built rubric."""
    metadata, statements = assemble(profile, project)
    header = CORE_HEADER if project is None or project.kind == "core" else plugin_header(project, profile)
    return render_rubric(metadata, statements, header)


def target_path(project, profile):
    if project is None or project.kind == "core":
        return profile.target
    if not project.build_dir:
        return None
    return os.path.join(project.build_dir, f"{profile.id}.rubric.yml")


def build_core():
    for profile in load_suite().profiles.values():
        _write(profile.target, rendered(None, profile))
    return 0


def build_plugin(path, out_dir=None):
    from .manifest import check_plugin

    project = load_project(path)
    problems = check_plugin(project)
    if problems:
        raise ManifestError(project.path, problems)
    out_dir = out_dir or project.build_dir or os.path.join(project.root, "build")
    written = []
    for profile in project.profiles:
        dest = os.path.join(out_dir, f"{profile.id}.rubric.yml")
        _write(dest, rendered(project, profile))
        written.append(dest)
    return written


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    count = text.split("\n---\n", 1)[1].count("\n- id: ")
    print(f"Wrote {os.path.relpath(path)} ({count} statements)")


def main(argv=None):
    import argparse

    parser = argparse.ArgumentParser(description="Build the core CAWG rubrics, or a plugin's rubrics.")
    parser.add_argument("--plugin", help="Plugin manifest (cawg-plugin.yml) or its directory")
    parser.add_argument("--out", help="Output directory for plugin rubrics (default: the plugin's build_dir)")
    args = parser.parse_args(argv)
    if not args.plugin:
        return build_core()
    try:
        build_plugin(args.plugin, args.out)
    except ManifestError as e:
        print(e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
